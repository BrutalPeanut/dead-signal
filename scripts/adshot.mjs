// Rewarded-ad placements with the sample provider (?ads=demo). node scripts/adshot.mjs <save.json> <outprefix>
import { chromium } from 'playwright';
import fs from 'node:fs';
const [save, out] = process.argv.slice(2);
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome', args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const errs = []; p.on('pageerror', (e) => errs.push(String(e)));
await p.goto('http://localhost:5173/?ads=demo&profile=adshot');
const s = JSON.parse(fs.readFileSync(save, 'utf8'));
s.seenIntro = true; s.lastDaily = new Date().toDateString(); s.keys = 0;
await p.evaluate((j) => localStorage.setItem('deadsignal.save.v1:adshot', j), JSON.stringify(s));
await p.reload(); await p.waitForTimeout(1000);
await p.locator('.nav button', { hasText: 'Supply' }).click(); await p.waitForTimeout(300);
await p.screenshot({ path: out + '-1-supply.png' });
await p.locator('.ad-btn').first().click(); await p.waitForTimeout(2500);
await p.screenshot({ path: out + '-2-playing.png' });
await p.waitForTimeout(13500);
await p.screenshot({ path: out + '-3-earned.png' });
await p.locator('.ad-close').click(); await p.waitForTimeout(500);
const keys = await p.evaluate(() => window.__ds.app.profile.data.keys);
await p.locator('.nav button', { hasText: 'Battle' }).click(); await p.waitForTimeout(300);
await p.locator('.battle-row .go').click(); await p.waitForTimeout(700);
await p.evaluate(() => { const g = window.__ds.app.game; g.revives = 0; window.__ds.advance(20); g.hp = -1; });
await p.waitForTimeout(800);
await p.screenshot({ path: out + '-4-revive.png' });
await p.locator('.modal .btn', { hasText: 'Give up' }).click(); await p.waitForTimeout(2600);
await p.screenshot({ path: out + '-5-results.png' });
console.log('keys after ad:', keys, '|', errs.join('\n') || 'no page errors');
await b.close();
