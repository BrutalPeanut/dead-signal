import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const errs = [];
page.on('pageerror', (e) => errs.push(String(e.stack || e)));
await page.goto('http://localhost:5173/');
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForTimeout(400);
await page.click('.modal .btn');
await page.waitForTimeout(1500);
await page.screenshot({ path: 'screens/lobby-new.png' });
await page.click('.nav button:nth-child(5)');
await page.waitForTimeout(300);
const toast = await page.evaluate(() => document.querySelector('.toast-item')?.textContent);
await page.evaluate(() => { const p = window.__ds.app.profile; p.data.unlocked = 6; p.data.stars = { 0: 7, 1: 7, 2: 7, 3: 7, 4: 3, 5: 1 }; p.save(); });
await page.click('.sc-title');
await page.waitForTimeout(500);
await page.screenshot({ path: 'screens/lobby-map.png' });
console.log('locked tab toast:', toast);
console.log(errs.length ? 'ERRORS:\n' + errs.join('\n') : 'clean');
await browser.close();
