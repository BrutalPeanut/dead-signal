// Screens for UI reviews: lobby, supply, armory, level-up, results, settings. node scripts/uitour2.mjs <save.json> <outdir>
import { chromium } from 'playwright';
import fs from 'node:fs';
const [save, out] = process.argv.slice(2);
fs.mkdirSync(out, { recursive: true });
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome', args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const errs = []; p.on('pageerror', (e) => errs.push(String(e)));
await p.goto('http://localhost:5173/?profile=uitour');
const s = JSON.parse(fs.readFileSync(save, 'utf8'));
s.seenIntro = true; s.lastDaily = new Date().toDateString(); s.keys = 4;
await p.evaluate((j) => localStorage.setItem('deadsignal.save.v1:uitour', j), JSON.stringify(s));
await p.reload(); await p.waitForTimeout(1200);
await p.screenshot({ path: out + '/1-lobby.png' });
await p.locator('.nav button', { hasText: 'Supply' }).click(); await p.waitForTimeout(400);
await p.screenshot({ path: out + '/2-supply.png' });
await p.locator('.nav button', { hasText: 'Armory' }).click(); await p.waitForTimeout(400);
await p.screenshot({ path: out + '/3-armory.png' });
await p.locator('.nav button', { hasText: 'Battle' }).click(); await p.waitForTimeout(300);
await p.locator('.topbar .icon-btn').click(); await p.waitForTimeout(300);
await p.screenshot({ path: out + '/4-settings.png' });
await p.locator('.modal').click({ position: { x: 5, y: 5 } }); await p.waitForTimeout(300);
await p.locator('.battle-row .go').click(); await p.waitForTimeout(600);
await p.evaluate(() => { const g = window.__ds.app.game; g.offers = [{ type: 'passive', id: 'chip', level: 1, isNew: true }, { type: 'weapon', id: 'arc', level: 1, isNew: true }, { type: 'passive', id: 'plating', level: 1, isNew: true }]; g.state = 'levelup'; });
await p.waitForTimeout(500);
await p.screenshot({ path: out + '/5-levelup.png' });
await p.locator('.modal .card').first().click(); await p.waitForTimeout(300);
await p.evaluate(() => { const g = window.__ds.app.game; g.revives = 0; g.hp = -1; });
await p.waitForTimeout(2600);
await p.screenshot({ path: out + '/6-results.png' });
console.log(errs.join('\n') || 'no page errors');
await b.close();
